    #[tokio::test]
    async fn test_risk_engine_scales_large_order() {
        let handle = start_risk_engine(RiskEngineConfig::default(), None, None);

        // Large order should be scaled (1 * 50000 = 50000 = 50% of 100k, exceeds 10% limit)
        let decision = handle
            .check_order("test", "BTCUSDT", OrderSide::Buy, dec!(1), dec!(50000))
            .await
            .unwrap();

        match decision {
            RiskDecision::Scaled { new_quantity, .. } => {
                // max_allowed = 100000 * 0.10 = 10000
                // scaled_quantity = 10000 / 50000 = 0.2
                assert_eq!(new_quantity, dec!(0.2));
            }
            _ => panic!("Expected Scaled decision, got {:?}", decision),
        }

        handle.shutdown().await.unwrap();
    }
